export function mapSearch(query: string) {
  return (
    'https://www.google.com/maps/search/?' +
    new URLSearchParams({ api: '1', query }).toString()
  );
}
export function mapEmbed(query: string) {
  return (
    'https://maps.google.com/maps?' +
    new URLSearchParams({
      q: query,
      output: 'embed',
      hl: 'ru',
      z: '15',
    }).toString()
  );
}
export function mapDirections(
  origin: string,
  destination: string,
  mode: TravelMode = 'transit',
  waypoints: string[] = [],
) {
  const params = new URLSearchParams({
    api: '1',
    origin,
    destination,
    travelmode: mode === 'none' ? 'transit' : mode,
  });
  if (waypoints.length && mode !== 'transit')
    params.set('waypoints', waypoints.slice(0, 3).join('|'));
  return 'https://www.google.com/maps/dir/?' + params.toString();
}
